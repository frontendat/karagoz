import { FULL_LAYOUT_BREAKPOINTS } from './breakpoints.ts'

/**
 * Custom properties flipped for the side-by-side layout. Every consumer reads them with a fallback holding the
 * single-panel value, so the narrow layout is the default and no JS is needed for first paint.
 */
const SIDE_BY_SIDE = {
  '--hf-pane-display': 'block',
  '--hf-handle-display': 'flex',
  '--hf-toggle-display': 'none',
  '--hf-tb-order': '-1',
  '--hf-tb-bw': '0 0 1px 0',
  '--hf-tb-px': '1.75rem',
  '--hf-next-order': '0',
  '--hf-next-me': '0px',
  '--hf-toc-flex': '0 1 auto',
  '--hf-toc-justify': 'flex-start',
  '--hf-lesson-minw': '300px',
  '--hf-sandbox-minw': '460px',
  '--hf-sandbox-me': '1.25rem',
}

/**
 * Generates `src/layout.css`: base rules plus one `@container hayali` block per supported `fullLayoutFrom` value.
 * Container queries cannot read `var()`, so every breakpoint has to be spelled out. Regenerate with `pnpm gen:layout`.
 */
export const layoutCss = () => {
  const declarations = Object.entries(SIDE_BY_SIDE)
    .map(([name, value]) => `    ${name}: ${value};`)
    .join('\n')
  const blocks = Object.entries(FULL_LAYOUT_BREAKPOINTS)
    .map(
      ([from, rem]) =>
        `@container hayali (min-width: ${rem}rem) {\n  .hf-root[data-from='${from}'] {\n${declarations}\n  }\n}\n`,
    )
    .join('\n')
  return `/* Generated by src/layout/layoutCss.ts (pnpm gen:layout). Do not edit. */
.hf [data-hf-pane] {
  min-width: 0;
}
.hf [data-hf-pane='lesson'] {
  min-width: var(--hf-lesson-minw, 0);
}
.hf [data-hf-pane='sandbox'] {
  min-width: var(--hf-sandbox-minw, 0);
}
.hf[data-panel='lesson'] [data-hf-pane='sandbox'],
.hf[data-panel='sandbox'] [data-hf-pane='lesson'] {
  display: var(--hf-pane-display, none);
}
.hf [data-hf-handle] {
  display: var(--hf-handle-display, none);
}
.hf [data-hf-toggle] {
  display: var(--hf-toggle-display, block);
}

${blocks}`
}
